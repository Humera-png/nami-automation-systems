// Optional AI enhancement layer for the deterministic audit engine
// (server/auditEngine.js). Only runs when GEMINI_API_KEY is set. Never
// generates the audit from scratch — it only refines a handful of
// already-generated fields, and any failure here (timeout, rate limit,
// malformed response) falls back to the deterministic result untouched.

const DEFAULT_MODEL = process.env.GEMINI_MODEL || 'gemini-2.0-flash';
const REQUEST_TIMEOUT_MS = 12000;
const MAX_RETRIES = 2;

const ALLOWED_KEYS = ['automationSummary', 'architectureTitle', 'expectedBusinessImpact', 'aiRole', 'humanControlPoints', 'recommendedSystems'];

function sleep(ms) {
  return new Promise((resolve) => setTimeout(resolve, ms));
}

function buildPrompt(engineResult, payload) {
  return `You are refining an automation audit report that was already generated by a deterministic rules engine. Improve the wording and specificity of the fields below using ONLY the process the business described — do not invent tools, numbers, or facts that aren't supported by it.

Business process described: "${payload.manualProcess}"
Automation goal: "${payload.automationGoal}"
Business type: "${payload.businessType}"

Current deterministic draft:
${JSON.stringify(
  {
    architectureTitle: engineResult.architectureTitle,
    automationSummary: engineResult.automationSummary,
    expectedBusinessImpact: engineResult.expectedBusinessImpact,
    aiRole: engineResult.aiRole,
    humanControlPoints: engineResult.humanControlPoints,
    recommendedSystems: engineResult.recommendedSystems
  },
  null,
  2
)}

Respond with ONLY a strict JSON object (no markdown fences, no prose) containing any of these keys you can meaningfully improve: automationSummary (string), architectureTitle (string), expectedBusinessImpact (string), aiRole (string), humanControlPoints (array of strings), recommendedSystems (array of strings). Omit any key you don't want to change.`;
}

function safeParseJson(text) {
  try {
    const trimmed = text.trim();
    const fenced = trimmed.match(/^```(?:json)?\s*([\s\S]*?)\s*```$/i);
    return JSON.parse(fenced ? fenced[1] : trimmed);
  } catch {
    return null;
  }
}

function sanitizeGeminiResult(parsed) {
  if (!parsed || typeof parsed !== 'object') return null;
  const out = {};
  for (const key of ALLOWED_KEYS) {
    const value = parsed[key];
    if (key === 'humanControlPoints' || key === 'recommendedSystems') {
      if (Array.isArray(value) && value.length > 0 && value.every((v) => typeof v === 'string' && v.trim().length > 0)) {
        out[key] = value.slice(0, 8).map((v) => v.trim().slice(0, 300));
      }
    } else if (typeof value === 'string' && value.trim().length > 0) {
      out[key] = value.trim().slice(0, 800);
    }
  }
  return Object.keys(out).length > 0 ? out : null;
}

async function callGeminiOnce(prompt, apiKey) {
  const controller = new AbortController();
  const timeoutId = setTimeout(() => controller.abort(), REQUEST_TIMEOUT_MS);
  try {
    return await fetch(`https://generativelanguage.googleapis.com/v1beta/models/${DEFAULT_MODEL}:generateContent?key=${apiKey}`, {
      method: 'POST',
      headers: { 'Content-Type': 'application/json' },
      signal: controller.signal,
      body: JSON.stringify({
        contents: [{ parts: [{ text: prompt }] }],
        generationConfig: { temperature: 0.4, responseMimeType: 'application/json' }
      })
    });
  } finally {
    clearTimeout(timeoutId);
  }
}

/**
 * Returns a sanitized partial-result object to merge on top of the
 * deterministic engine output, or `null` if enhancement isn't available
 * or fails for any reason. Never throws — every failure path (timeout,
 * 429/503, malformed JSON, empty response) resolves to `null` so the
 * caller can safely fall back to the deterministic result with HTTP 200.
 */
export async function enhanceWithGemini(engineResult, payload) {
  const apiKey = process.env.GEMINI_API_KEY;
  if (!apiKey) return null;

  const prompt = buildPrompt(engineResult, payload);

  for (let attempt = 0; attempt <= MAX_RETRIES; attempt++) {
    let response;
    try {
      response = await callGeminiOnce(prompt, apiKey);
    } catch (err) {
      if (err.name === 'AbortError') {
        // eslint-disable-next-line no-console
        console.error('[gemini] Request timed out after', REQUEST_TIMEOUT_MS, 'ms.');
        return null;
      }
      // eslint-disable-next-line no-console
      console.error('[gemini] Network error:', err.message);
      if (attempt < MAX_RETRIES) {
        await sleep(2 ** attempt * 500);
        continue;
      }
      return null;
    }

    if (response.status === 429 || response.status === 503) {
      if (attempt < MAX_RETRIES) {
        await sleep(2 ** attempt * 500);
        continue;
      }
      // eslint-disable-next-line no-console
      console.error('[gemini] Exhausted retries after repeated', response.status, 'responses.');
      return null;
    }

    if (!response.ok) {
      // eslint-disable-next-line no-console
      console.error('[gemini] Non-2xx response:', response.status);
      return null;
    }

    let json;
    try {
      json = await response.json();
    } catch (err) {
      // eslint-disable-next-line no-console
      console.error('[gemini] Failed to parse response body as JSON:', err.message);
      return null;
    }

    const text = json?.candidates?.[0]?.content?.parts?.[0]?.text;
    if (!text) return null;

    const parsed = safeParseJson(text);
    return sanitizeGeminiResult(parsed);
  }

  return null;
}
